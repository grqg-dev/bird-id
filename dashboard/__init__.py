"""Local web dashboard for bird-id (package).

Split from the old single-file `dashboard.py`:

- `app.py`    — Flask `app`, `_CFG`, `_db()`, slug helpers, `main()`
- `api.py`    — JSON APIs and the `/dash` React SPA host
- `media.py`  — audio, spectrogram, sprites, callviz/vibeviz, `/call` + `/vibe`
- `legacy.py` — server-rendered template pages

Everything the rest of the project (and the tests) used from the old module is
re-exported here, so `import dashboard; dashboard._db` etc. keep working.
Tests monkeypatch `dashboard._db`, `_today`, `_CACHE`, `_DASH_DIST`; submodules
read those through the package at call time.

Run:
    ./.venv/bin/python birdid.py dashboard
    ./.venv/bin/python -m dashboard
"""

